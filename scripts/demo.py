#!/usr/bin/env python3
"""Ten-step walkthrough of the main result (`make demo`). Every step checks its own outcome.

The RTL never changes: only the authenticated policy does. Exit status 1 on any unexpected result.
usage: demo.py --fw build/fw/fw_demo[.exe]   (packages in build/pkgs, corpus in build/traces)
"""
from __future__ import annotations

import argparse
import dataclasses
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import run_rtl  # noqa: E402  (also puts tools/ on sys.path)
import trace_validator as tv  # noqa: E402
from hsm_common import E, E_NAME, OWNER_NAME, V_NAME, load_policy, policy_hex_words, policy_to_json, write_hex  # noqa: E402
from policy_generator import example_policies  # noqa: E402

D = Path("build/demo")
LEGIT = dict(master=1, addr=0x1000_0100, op="W", priv=0, burst=8)   # DMA writes its own buffer
ATTACK = dict(master=1, addr=0x1000_8000, op="W", priv=0, burst=4)  # scenario 1: DMA reaches a protected page
failed = []


def require(ok: bool, what: str):
    if not ok:
        failed.append(what)
        print(f"   !! UNEXPECTED: {what}")


def txt(t):
    return f"DMA {'write' if t['op'] == 'W' else 'read'} 0x{t['addr']:08X}, {t['burst']} beats"


def rtl(base, update=None, enforced=None):
    """Boot-restore `base` on the bounded RTL (MODE 2), optionally install `update` through the real
    requester -> validator -> idle-boundary switch path, then decide LEGIT and ATTACK. The testbench
    checks every decision against the reference model of `enforced`, the policy that must now be active."""
    enforced = enforced or base
    tag = f"{base.name}_{update.name if update else 'only'}"
    write_hex(ROOT / D / f"{base.name}.hex", policy_hex_words(base))
    args = [f"+policy={D}/{base.name}.hex", f"+vectors={D}/{tag}.vec", f"+out={D}/{tag}.dec", "+check"]
    if update:
        write_hex(ROOT / D / f"{update.name}.hex", policy_hex_words(update))
        args.append(f"+attack={D}/{update.name}.hex")
    tv.export_rtl(enforced, [LEGIT, ATTACK], ROOT / D / f"{tag}.vec")
    out = run_rtl.run_vvp(rtl.vvp, args)
    res = run_rtl.result(out)
    require(res is not None and res[3] == "PASS", f"RTL run {tag} (decisions vs reference model of {enforced.name})")
    m = re.search(r"ATTACK accepted=(\d) err=(\d+)", out)
    dec = [tuple(map(int, l.split()[1:])) for l in (ROOT / D / f"{tag}.dec").read_text().split("\n") if l.strip()]
    return (m and (m.group(1) == "1", int(m.group(2)))), dec


def show(dec, i):
    allow, reason = dec[i]
    return "ALLOW" if allow else f"DENY ({V_NAME[reason]})"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--fw", required=True, help="firmware demo binary")
    a = ap.parse_args(argv)
    rtl.vvp = run_rtl.compile_tb("tb_security_monitor", {"MODE": 2})
    v1 = load_policy(ROOT / "examples/policy_v1.json")
    v2 = load_policy(ROOT / "examples/policy_v2.json")

    print("[1] Initial policy v1 (factory, installed through the boot window)")
    for r in v1.rules:
        perm = ("R" if r.read else "") + ("W" if r.write else "") + (" priv" if r.priv else "")
        print(f"      slot {r.slot}: {OWNER_NAME[r.owner]:4} 0x{r.start:08X}-0x{r.end:08X} {perm:7} burst<={r.max_burst}")

    _, dec = rtl(v1)
    print(f"[2] RTL, policy v1: {txt(LEGIT)} -> {show(dec, 0)}")
    require(dec[0][0] == 1, "legitimate DMA write allowed under v1")
    print(f"[3] RTL, policy v1: {txt(ATTACK)} -> {show(dec, 1)}")
    print("      ^ the vulnerability: scenario 1 says DMA must not reach 0x10008000-0x10008FFF")
    require(dec[1][0] == 1, "scenario-1 transaction allowed under v1 (the weakness)")

    gen = example_policies()["policy_v2"]
    same = policy_to_json(gen) == json.loads((ROOT / "examples/policy_v2.json").read_text())
    print("[4] New policy generated by the DMA owner: policy_v2 (requester DMA, version 2)")
    print("      DMA window split into 0x10000000-0x10007FFF and 0x10009000-0x1000FFFF;"
          f" regenerated by policy_generator: {'identical' if same else 'DIFFERENT'}")
    require(same, "policy_generator reproduces examples/policy_v2.json")

    print("[5] Trace-based evaluation before signing (477-transaction corpus, offline release gate)")
    gate = [("policy_v1", "policy_v2", "recommend"), ("policy_v2", "policy_v3", "recommend"),
            ("policy_v3", "policy_v4", "recommend"), ("policy_v1", "candidates/cand_v2_overbroad", "reject"),
            ("policy_v4", "candidates/cand_v5_dma_reopen", "reject")]
    for base, cand, expect in gate:
        name = Path(cand).name
        r = subprocess.run([sys.executable, "tools/trace_validator.py", "compare", "--trace", "build/traces/corpus.csv",
                            "--baseline", f"examples/{base}.json", "--candidate", f"examples/{cand}.json",
                            "--expect", expect, "--report", f"build/reports/{name}.md"],
                           cwd=ROOT, capture_output=True, text=True)
        print(f"      {base} -> {name:22} {expect.upper():9} {'as expected' if r.returncode == 0 else 'WRONG VERDICT'}"
              f"  (report: build/reports/{name}.md)")
        require(r.returncode == 0, f"gate verdict {expect} for {name}")

    bad = dataclasses.replace(v2, name="bad_dma_widen", rules=[
        dataclasses.replace(r, end=0x1001_0FFF) if r.slot == 3 else r for r in v2.rules])
    (acc, err), dec = rtl(v1, bad, enforced=v1)
    print("[6] Malicious update: DMA-signed candidate widening slot 3 to 0x10010FFF (outside DMA's envelope)")
    print(f"      hardware validator -> {'ACCEPTED' if acc else 'REJECTED ' + E_NAME[err]}; active policy unchanged"
          f" (v1: the scenario-1 write is still {show(dec, 1)})")
    require(not acc and err == E["ADDR_ESCAPE"], "hardware rejects the out-of-envelope update with ADDR_ESCAPE")

    (acc, err), dec = rtl(v1, v2, enforced=v2)
    print("[7] Valid restricted policy v2 staged in the inactive bank, requester DMA -> hardware validator: "
          + ("ACCEPTED" if acc else "REJECTED " + E_NAME[err]))
    print("[8] ACTIVATE: transactions held, one-bit bank switch at an idle boundary, CONFIRM -> v2 active")
    require(acc, "v2 accepted and activated")
    print(f"[9] Same RTL, policy v2: {txt(ATTACK)} -> {show(dec, 1)}")
    print(f"                         {txt(LEGIT)} -> {show(dec, 0)}")
    require(dec[1][0] == 0 and dec[0][0] == 1, "attack now denied, legitimate traffic still allowed")

    print("[10] Device run: C policy manager + host hardware model (v1 -> v2 -> v3 -> v4, power cut after"
          " activating v4)")
    fw = subprocess.run([str((ROOT / a.fw).resolve()), "build/pkgs", "build/fw/mmio_demo.log"], cwd=ROOT, capture_output=True, text=True)
    print("\n".join("      " + l for l in fw.stdout.splitlines()))
    require(fw.returncode == 0 and "DEMO_RESULT PASS" in fw.stdout, "firmware demo (recovery to committed v3)")
    out = run_rtl.run_vvp(run_rtl.compile_tb("tb_mmio_replay"), ["+log=build/fw/mmio_demo.log"])
    res = run_rtl.result(out)
    replay = " ".join(l for l in out.splitlines() if l.startswith("REPLAY"))
    print(f"      same register traffic replayed into the RTL: {res[3] if res else 'FAIL'} {replay}")
    require(res is not None and res[3] == "PASS", "RTL replay of the firmware's register traffic")

    print(f"DEMO {'PASS' if not failed else 'FAIL: ' + '; '.join(failed)}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""Generate test keys and sign / inspect policy packages (Ed25519 via `cryptography`).

  keygen  --keys build/keys --c-out build/gen/device_config.c   (keeps existing keys)
  sign    --policy P.json --keys build/keys --out P.hsmp [--key-owner NAME]
  verify  --pkg P.hsmp --keys build/keys
  inspect --pkg P.hsmp
  testset --keys build/keys --examples examples --out build/pkgs   (all packages used by tests)

Private keys are written only under build/ (git-ignored). The firmware receives the
PUBLIC keys through a generated device-configuration file, never from a package.
"""
from __future__ import annotations

import argparse
import struct
import sys
from dataclasses import replace
from pathlib import Path

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey, Ed25519PublicKey
from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat

sys.path.insert(0, str(Path(__file__).resolve().parent))
from hsm_common import (DEVICE_ID, HDR_SIGNED, OWNERS, OWNER_NAME, Policy, Rule, encode_rules,  # noqa: E402
                        load_policy, parse_package, signed_header, validate_update)

KEY_ORDER = ["CPU", "DMA", "DIAG", "ROOT"]   # trusted key table index == owner id (ROOT -> 3)


def key_path(keys: Path, name: str) -> Path:
    return keys / f"{name.lower()}.key"


def load_key(keys: Path, name: str) -> Ed25519PrivateKey:
    return Ed25519PrivateKey.from_private_bytes(bytes.fromhex(key_path(keys, name).read_text().strip()))


def pub_bytes(k: Ed25519PrivateKey) -> bytes:
    return k.public_key().public_bytes(Encoding.Raw, PublicFormat.Raw)


def keygen(keys: Path, c_out: Path):
    keys.mkdir(parents=True, exist_ok=True)
    for name in KEY_ORDER:
        p = key_path(keys, name)
        if not p.exists():
            p.write_text(Ed25519PrivateKey.generate().private_bytes_raw().hex() + "\n")
    rows = ",\n".join("    {" + ", ".join(f"0x{b:02x}" for b in pub_bytes(load_key(keys, n))) + "}  /* " + n + " */"
                      for n in KEY_ORDER)
    c_out.parent.mkdir(parents=True, exist_ok=True)
    c_out.write_text(
        "/* GENERATED by tools/policy_signer.py keygen - device configuration (public data only). */\n"
        '#include "device_config.h"\n\n'
        f"const uint32_t hsm_device_id = 0x{DEVICE_ID:08X}u;\n\n"
        f"const uint8_t hsm_trusted_keys[HSM_NUM_KEYS][32] = {{\n{rows}\n}};\n")


def build_package(p: Policy, key: Ed25519PrivateKey, count: int | None = None) -> bytes:
    payload = encode_rules(p.rules)
    hdr = signed_header(p, payload, count)
    assert len(hdr) == HDR_SIGNED
    return hdr + key.sign(hdr) + payload


def signer_name(p: Policy) -> str:
    return OWNER_NAME[p.requester]


def verify(blob: bytes, keys: Path) -> dict:
    d = parse_package(blob)
    pub: Ed25519PublicKey = load_key(keys, OWNER_NAME[d["requester"]]).public_key()
    pub.verify(d["signature"], d["signed"])   # raises InvalidSignature
    import hashlib
    if hashlib.blake2b(d["payload"], digest_size=32).digest() != d["digest"]:
        raise ValueError("payload digest mismatch")
    return d


def testset(keys: Path, examples: Path, out: Path):
    """Every package the C tests and the demo use, including deliberately malformed ones."""
    out.mkdir(parents=True, exist_ok=True)
    n = 0

    def emit(name, blob):
        nonlocal n
        (out / f"{name}.hsmp").write_bytes(blob)
        n += 1

    pols = {}
    for f in sorted(examples.rglob("*.json")):
        pol = load_policy(f)
        pols[f.stem] = pol
        emit(f.stem, build_package(pol, load_key(keys, signer_name(pol))))

    v2, v4 = pols["policy_v2"], pols["policy_v4"]
    dma = load_key(keys, "DMA")
    emit("neg_wrong_device", build_package(replace(v2, device_id=0xDEADBEEF), dma))
    emit("neg_wrong_key", build_package(v2, load_key(keys, "CPU")))          # requester DMA, CPU signature
    emit("neg_root_runtime", build_package(replace(v4, requester=OWNERS["ROOT"], version=5, prev_version=4),
                                           load_key(keys, "ROOT")))
    emit("neg_unknown_owner", build_package(replace(v4, requester=5, version=5, prev_version=4), dma))
    nine = [Rule(i % 8, 1, 0x1000_0000 + i * 16, 0x1000_000F + i * 16, True, True, False, 4) for i in range(9)]
    emit("neg_count9", build_package(replace(v4, rules=nine, version=5, prev_version=4), dma))
    dup = v4.rules + [replace(v4.rules[1], start=0x1000_E000)]
    emit("neg_dup_slot", build_package(replace(v4, rules=dup, version=5, prev_version=4), dma))
    # reserved flag bit 7 set in rule 0: re-sign so only the encoding check can catch it
    bad = replace(v4, version=5, prev_version=4)
    payload = bytearray(encode_rules(bad.rules)); payload[10] |= 0x80
    hdr = signed_header(bad, bytes(payload))
    emit("neg_bad_flags", hdr + dma.sign(hdr) + bytes(payload))
    # Reference-model prediction of the hardware verdict for each attack (checked by the C tests)
    lines = []
    for name, pol in sorted(pols.items()):
        if name.startswith("atk_"):
            err, slot = validate_update(pol, v4.rules, v4.version)
            lines.append(f"{name} {err} {slot}\n")
    (out / "expected_hw.txt").write_text("".join(lines))
    return n


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    k = sub.add_parser("keygen"); k.add_argument("--keys", default="build/keys"); k.add_argument("--c-out", default="build/gen/device_config.c")
    s = sub.add_parser("sign"); s.add_argument("--policy", required=True); s.add_argument("--keys", default="build/keys")
    s.add_argument("--out", required=True); s.add_argument("--key-owner", help="override signing key (testing)")
    v = sub.add_parser("verify"); v.add_argument("--pkg", required=True); v.add_argument("--keys", default="build/keys")
    i = sub.add_parser("inspect"); i.add_argument("--pkg", required=True)
    t = sub.add_parser("testset"); t.add_argument("--keys", default="build/keys"); t.add_argument("--examples", default="examples")
    t.add_argument("--out", default="build/pkgs")
    a = ap.parse_args(argv)

    if a.cmd == "keygen":
        keygen(Path(a.keys), Path(a.c_out))
        print(f"keys in {a.keys}/ (private, git-ignored); public table -> {a.c_out}")
    elif a.cmd == "sign":
        pol = load_policy(a.policy)
        blob = build_package(pol, load_key(Path(a.keys), a.key_owner or signer_name(pol)))
        Path(a.out).parent.mkdir(parents=True, exist_ok=True)
        Path(a.out).write_bytes(blob)
        print(f"{a.out}: {len(blob)} bytes, requester {signer_name(pol)}, v{pol.version}")
    elif a.cmd == "verify":
        try:
            d = verify(Path(a.pkg).read_bytes(), Path(a.keys))
        except (InvalidSignature, ValueError, KeyError) as e:
            print(f"INVALID: {type(e).__name__} {e}")
            return 1
        print(f"OK: requester {OWNER_NAME[d['requester']]}, version {d['version']}, {d['count']} rules")
    elif a.cmd == "inspect":
        d = parse_package(Path(a.pkg).read_bytes())
        print(f"device 0x{d['device_id']:08X} requester {OWNER_NAME.get(d['requester'], d['requester'])} "
              f"version {d['version']} (prev {d['prev_version']}) rules {d['count']}")
        for r in d["rules"]:
            print("  " + r.describe())
    else:
        print(f"wrote {testset(Path(a.keys), Path(a.examples), Path(a.out))} packages to {a.out}/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
